create or replace function public.record_events(p_organization_id uuid, p_events jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_results jsonb := '[]'::jsonb;
  v_result  jsonb;
  v_code    text;
  v_message text;
  v_i       integer;
begin
  if jsonb_typeof(p_events) <> 'array' then
    perform _event_error('invalid_batch', 'events must be a JSON array', '22023');
  end if;
  if jsonb_array_length(p_events) > 100 then
    perform _event_error('batch_too_large', 'A batch can contain at most 100 events', '22023');
  end if;

  for v_i in 0 .. jsonb_array_length(p_events) - 1 loop
    v_result := null; v_code := null; v_message := null;
    begin
      v_result := _record_member_event(p_organization_id, p_events -> v_i);
    exception when others then
      get stacked diagnostics v_code = pg_exception_hint, v_message = message_text;
    end;
    v_results := v_results || _event_result(v_i, v_result, v_code, v_message);
  end loop;
  return v_results;
end;
$$;

comment on function public.record_events(uuid, jsonb) is
  'Records up to 100 events (e.g. a reconnect queue). Each event succeeds or fails on its own; returns one result per event.';

-- --------------------------------------------------------------------
-- Floor sessions
-- --------------------------------------------------------------------
create or replace function public._floor_session(p_session_token text)
returns public.floor_sessions
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.floor_sessions;
begin
  select s.* into v_session
  from floor_sessions s
  join floor_worker_credentials c on c.id = s.credential_id and c.is_active
  join organization_members m on m.id = s.member_id and m.is_active
  where s.token_hash = _hash_session_token(p_session_token)
    and s.revoked_at is null
    and s.expires_at > now();

  if v_session.id is null then
    perform _event_error('session_invalid', 'Your floor session has ended. Sign in again with your badge.', '42501');
  end if;

  update floor_sessions set last_seen_at = now()
  where id = v_session.id and last_seen_at < now() - interval '1 minute';

  return v_session;
end;
$$;

