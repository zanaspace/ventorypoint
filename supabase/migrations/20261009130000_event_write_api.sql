-- --------------------------------------------------------------------
-- Payload validation: JSON Schema subset
-- Supported keywords: type (object, array, string, number, integer, boolean,
-- null), required, properties, additionalProperties (false), items, enum,
-- minimum, maximum, exclusiveMinimum, exclusiveMaximum, minLength, maxLength,
-- minItems, maxItems. Unknown keywords are ignored.
-- Returns a list of error strings (empty = valid).
-- --------------------------------------------------------------------
create or replace function public.validate_event_payload(
  p_schema jsonb,
  p_value  jsonb,
  p_path   text default '$'
)
returns text[]
language plpgsql
immutable
set search_path = public
as $$
declare
  v_errors   text[] := '{}';
  v_type     text := p_schema ->> 'type';
  v_actual   text := jsonb_typeof(p_value);
  v_key      text;
  v_sub      jsonb;
  v_i        integer;
  v_num      numeric;
  v_len      integer;
begin
  if p_schema is null or jsonb_typeof(p_schema) <> 'object' then
    return v_errors;
  end if;

  if p_value is null then
    return array[format('%s: value is missing', p_path)];
  end if;

  -- type
  if v_type is not null then
    if v_type = 'integer' then
      if v_actual <> 'number' or (p_value #>> '{}')::numeric <> trunc((p_value #>> '{}')::numeric) then
        return array[format('%s: expected integer, got %s', p_path, v_actual)];
      end if;
    elsif v_type <> v_actual then
      return array[format('%s: expected %s, got %s', p_path, v_type, v_actual)];
    end if;
  end if;

  -- enum
  if p_schema ? 'enum' and not (p_schema -> 'enum') @> jsonb_build_array(p_value) then
    v_errors := v_errors || format('%s: value is not one of %s', p_path, p_schema -> 'enum');
  end if;

  -- numbers
  if v_actual = 'number' then
    v_num := (p_value #>> '{}')::numeric;
    if p_schema ? 'minimum' and v_num < (p_schema ->> 'minimum')::numeric then
      v_errors := v_errors || format('%s: must be >= %s', p_path, p_schema ->> 'minimum');
    end if;
    if p_schema ? 'maximum' and v_num > (p_schema ->> 'maximum')::numeric then
      v_errors := v_errors || format('%s: must be <= %s', p_path, p_schema ->> 'maximum');
    end if;
    if p_schema ? 'exclusiveMinimum' and v_num <= (p_schema ->> 'exclusiveMinimum')::numeric then
      v_errors := v_errors || format('%s: must be > %s', p_path, p_schema ->> 'exclusiveMinimum');
    end if;
    if p_schema ? 'exclusiveMaximum' and v_num >= (p_schema ->> 'exclusiveMaximum')::numeric then
      v_errors := v_errors || format('%s: must be < %s', p_path, p_schema ->> 'exclusiveMaximum');
    end if;
  end if;

  -- strings
  if v_actual = 'string' then
    v_len := char_length(p_value #>> '{}');
    if p_schema ? 'minLength' and v_len < (p_schema ->> 'minLength')::integer then
      v_errors := v_errors || format('%s: must be at least %s characters', p_path, p_schema ->> 'minLength');
    end if;
    if p_schema ? 'maxLength' and v_len > (p_schema ->> 'maxLength')::integer then
      v_errors := v_errors || format('%s: must be at most %s characters', p_path, p_schema ->> 'maxLength');
    end if;
  end if;

  -- objects
  if v_actual = 'object' then
    if jsonb_typeof(p_schema -> 'required') = 'array' then
      for v_key in select jsonb_array_elements_text(p_schema -> 'required') loop
        if not p_value ? v_key or jsonb_typeof(p_value -> v_key) = 'null' then
          v_errors := v_errors || format('%s.%s: is required', p_path, v_key);
        end if;
      end loop;
    end if;

    if jsonb_typeof(p_schema -> 'properties') = 'object' then
      for v_key, v_sub in select * from jsonb_each(p_schema -> 'properties') loop
        if p_value ? v_key and jsonb_typeof(p_value -> v_key) <> 'null' then
          v_errors := v_errors || public.validate_event_payload(v_sub, p_value -> v_key, p_path || '.' || v_key);
        end if;
      end loop;
    end if;

    if (p_schema -> 'additionalProperties') = 'false'::jsonb then
      for v_key in select jsonb_object_keys(p_value) loop
        if not coalesce(p_schema -> 'properties', '{}'::jsonb) ? v_key then
          v_errors := v_errors || format('%s.%s: is not allowed', p_path, v_key);
        end if;
      end loop;
    end if;
  end if;

  -- arrays
  if v_actual = 'array' then
    v_len := jsonb_array_length(p_value);
    if p_schema ? 'minItems' and v_len < (p_schema ->> 'minItems')::integer then
      v_errors := v_errors || format('%s: needs at least %s items', p_path, p_schema ->> 'minItems');
    end if;
    if p_schema ? 'maxItems' and v_len > (p_schema ->> 'maxItems')::integer then
      v_errors := v_errors || format('%s: allows at most %s items', p_path, p_schema ->> 'maxItems');
    end if;
    if jsonb_typeof(p_schema -> 'items') = 'object' then
      for v_i in 0 .. v_len - 1 loop
        v_errors := v_errors || public.validate_event_payload(p_schema -> 'items', p_value -> v_i, format('%s[%s]', p_path, v_i));
      end loop;
    end if;
  end if;

  return v_errors;
end;
$$;

comment on function public.validate_event_payload(jsonb, jsonb, text) is
  'Validates a JSON value against a JSON Schema subset; returns error messages (empty array = valid).';

-- --------------------------------------------------------------------
-- Core insert (internal: never granted to clients)
-- Callers must already have authorized the organization/actor; this function
-- validates the event itself and makes the write idempotent.
-- Returns {"event_id": uuid, "status": "created" | "duplicate"}.
-- --------------------------------------------------------------------
create or replace function public._insert_event(
  p_organization_id      uuid,
  p_event                jsonb,
  p_actor_user_id        uuid,
  p_actor_worker_id      uuid,
  p_device_id            uuid,
  p_source               text,
  p_allow_backdate       boolean,
  p_backdate_approved_by uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_key          text := nullif(trim(p_event ->> 'idempotency_key'), '');
  v_type         text := p_event ->> 'event_type';
  v_version      integer := coalesce((p_event ->> 'event_version')::integer, 1);
  v_payload      jsonb := coalesce(p_event -> 'payload', '{}'::jsonb);
  v_facility_id  uuid := (p_event ->> 'facility_id')::uuid;
  v_client_id    uuid := (p_event ->> 'client_account_id')::uuid;
  v_occurred_at  timestamptz := coalesce((p_event ->> 'occurred_at')::timestamptz, now());
  v_registry     public.event_type_registry;
  v_device       public.floor_devices;
  v_errors       text[];
  v_existing     uuid;
  v_event_id     uuid := gen_random_uuid();
  v_partition    text;
begin
  -- 1. Idempotency first: a retried request returns the original event even if
  --    it would now fail time checks (e.g. a scan queued offline for hours).
  if v_key is null or char_length(v_key) not between 8 and 200 then
    perform _event_error('invalid_idempotency_key', 'idempotency_key must be 8 to 200 characters', '22023');
  end if;

  select event_id into v_existing
  from event_idempotency_keys
  where organization_id = p_organization_id and idempotency_key = v_key;
  if v_existing is not null then
    return jsonb_build_object('event_id', v_existing, 'status', 'duplicate');
  end if;

  -- 2. Event type and payload
  select * into v_registry
  from event_type_registry
  where event_type = v_type and version = v_version and is_active;
  if v_registry.event_type is null then
    perform _event_error('unknown_event_type', format('Unknown or inactive event type %s v%s', v_type, v_version), '22023');
  end if;

  if jsonb_typeof(v_payload) <> 'object' then
    perform _event_error('invalid_payload', 'payload must be a JSON object', '22023');
  end if;
  v_errors := validate_event_payload(v_registry.payload_schema, v_payload);
  if cardinality(v_errors) > 0 then
    perform _event_error('invalid_payload', 'Invalid payload: ' || array_to_string(v_errors, '; '), '22023');
  end if;

  -- 3. Time bounds (2 minutes of clock skew allowed)
  if v_occurred_at > now() + interval '2 minutes' then
    perform _event_error('occurred_in_future', 'occurred_at cannot be in the future', '22023');
  end if;
  if v_occurred_at < now() - interval '72 hours' and not coalesce(p_allow_backdate, false) then
    perform _event_error('occurred_too_old',
      'occurred_at is more than 72 hours ago; a supervisor must approve back-dated events', '22023');
  end if;

  -- 4. Scope integrity
  if v_facility_id is not null and not exists (
    select 1 from facilities where id = v_facility_id and organization_id = p_organization_id
  ) then
    perform _event_error('scope_denied', 'Facility does not belong to this organization', '42501');
  end if;
  if v_client_id is not null and not exists (
    select 1 from client_accounts where id = v_client_id and organization_id = p_organization_id
  ) then
    perform _event_error('scope_denied', 'Client account does not belong to this organization', '42501');
  end if;

  -- 5. Devices: floor events need a known, authorized, active device of this organization
  if p_device_id is not null then
    select * into v_device from floor_devices where id = p_device_id;
    if v_device.id is null or v_device.organization_id <> p_organization_id then
      perform _event_error('unknown_device', 'Device is not registered to this organization', '42501');
    elsif v_device.retired_at is not null then
      perform _event_error('device_retired', 'This device has been retired', '42501');
    elsif v_device.blocked_at is not null then
      perform _event_error('device_blocked', 'This device has been blocked by a supervisor', '42501');
    elsif not v_device.is_authorized then
      perform _event_error('device_not_authorized', 'This device is waiting for a supervisor to authorize it', '42501');
    end if;
  end if;
  if v_registry.is_floor_event and p_device_id is null then
    perform _event_error('device_required', format('%s must be recorded from a registered device', v_type), '42501');
  end if;

  -- 6. Partition for back-dated events (current months are pre-created)
  v_partition := format('warehouse_events_y%s', to_char(v_occurred_at at time zone 'UTC', 'YYYY"m"MM'));
  if to_regclass('public.' || v_partition) is null then
    perform ensure_warehouse_event_partition((v_occurred_at at time zone 'UTC')::date);
  end if;

  -- 7. Insert event + key together; a concurrent duplicate loses the race on the
  --    key's primary key, rolls back its event row and returns the winner's ID.
  begin
    insert into warehouse_events (
      id, organization_id, facility_id, client_account_id, event_type, event_version,
      entity_type, entity_id, payload, actor_user_id, actor_worker_id, device_id, source,
      correlation_id, causation_id, idempotency_key, occurred_at,
      backdate_reason, backdate_approved_by
    ) values (
      v_event_id, p_organization_id, v_facility_id, v_client_id, v_type, v_version,
      coalesce(nullif(p_event ->> 'entity_type', ''), v_registry.entity_type),
      (p_event ->> 'entity_id')::uuid, v_payload, p_actor_user_id, p_actor_worker_id, p_device_id, p_source,
      (p_event ->> 'correlation_id')::uuid, (p_event ->> 'causation_id')::uuid, v_key, v_occurred_at,
      case when p_backdate_approved_by is not null then p_event ->> 'backdate_reason' end,
      p_backdate_approved_by
    );

    insert into event_idempotency_keys (organization_id, idempotency_key, event_id, occurred_at)
    values (p_organization_id, v_key, v_event_id, v_occurred_at);
  exception when unique_violation then
    select event_id into v_existing
    from event_idempotency_keys
    where organization_id = p_organization_id and idempotency_key = v_key;
    if v_existing is null then
      raise;
    end if;
    return jsonb_build_object('event_id', v_existing, 'status', 'duplicate');
  end;

  -- 8. Last seen, throttled to one write per device per minute
  if p_device_id is not null then
    update floor_devices set last_active_at = now()
    where id = p_device_id and (last_active_at is null or last_active_at < now() - interval '1 minute');
  end if;

  return jsonb_build_object('event_id', v_event_id, 'status', 'created');
end;
$$;

-- Runs one event through an entry point and converts failures into a result row.
create or replace function public._event_result(p_index integer, p_result jsonb, p_code text, p_message text)
returns jsonb
language sql
immutable
as $$
  select case
    when p_result is not null then jsonb_build_object('index', p_index) || p_result
    else jsonb_build_object('index', p_index, 'status', 'error', 'code', coalesce(nullif(p_code, ''), 'error'), 'message', p_message)
  end
$$;

-- --------------------------------------------------------------------
-- Entry point 1: signed-in members
-- --------------------------------------------------------------------
create or replace function public._record_member_event(p_organization_id uuid, p_event jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid         uuid := auth.uid();
  v_role        member_role;
  v_facility_id uuid := (p_event ->> 'facility_id')::uuid;
  v_backdate    boolean := nullif(trim(p_event ->> 'backdate_reason'), '') is not null;
begin
  if v_uid is null then
    perform _event_error('not_authenticated', 'Sign in to record events', '42501');
  end if;

  v_role := get_user_role(p_organization_id);
  if v_role is null or v_role = 'client_user' then
    perform _event_error('scope_denied', 'You cannot record events for this organization', '42501');
  end if;

  if v_facility_id is not null and not user_has_facility(v_facility_id) then
    perform _event_error('scope_denied', 'You do not have access to this facility', '42501');
  end if;

  if v_backdate and v_role not in ('owner', 'admin', 'ops_manager', 'supervisor') then
    perform _event_error('backdate_not_allowed', 'Only supervisors and above can approve back-dated events', '42501');
  end if;

  return _insert_event(
    p_organization_id, p_event,
    v_uid, null,
    (p_event ->> 'device_id')::uuid,
    'web',
    v_backdate,
    case when v_backdate then v_uid end
  );
end;
$$;

