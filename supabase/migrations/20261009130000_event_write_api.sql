    'organization_name', o.name,
    'all_facilities', m.all_facilities,
    'device', case when d.id is null then null else jsonb_build_object(
      'id', d.id, 'name', d.device_name, 'is_authorized', d.is_authorized and d.retired_at is null,
      'is_blocked', d.blocked_at is not null,
      'facility_id', d.facility_id) end
  ) into v_result
  from organization_members m
  join floor_worker_credentials c on c.id = v_session.credential_id
  join organizations o on o.id = v_session.organization_id
  left join profiles p on p.id = m.user_id
  left join floor_devices d on d.id = v_session.device_id
  where m.id = v_session.member_id;

  return v_result;
end;
$$;

create or replace function public.end_floor_session(p_session_token text)
returns void
language sql
security definer
set search_path = public
as $$
  update floor_sessions set revoked_at = now()
  where token_hash = _hash_session_token(p_session_token) and revoked_at is null
$$;

-- Floor login now creates a server-side session and registers unknown devices.
-- Same signature and fields as Sprint 1, plus session_token / session_expires_at / device.
create or replace function public.floor_worker_login(
  p_badge_token  text,
  p_pin          text,
  p_device_token text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_cred    public.floor_worker_credentials;
  v_member  public.organization_members;
  v_profile public.profiles;
  v_org     public.organizations;
  v_device  public.floor_devices;
  v_token   text;
  v_expires timestamptz := now() + interval '12 hours';
  v_device_token text := nullif(trim(coalesce(p_device_token, '')), '');
begin
  select * into v_cred from public.floor_worker_credentials
  where badge_token = trim(p_badge_token) and is_active = true
  limit 1;

  if v_cred.id is null then
    return jsonb_build_object('ok', false, 'error', 'Invalid badge token. Please check your badge.');
  end if;

  if v_cred.locked_until is not null and v_cred.locked_until > now() then
    return jsonb_build_object(
      'ok', false,
      'locked', true,
      'error', 'Account is locked due to multiple failed attempts. Please ask a supervisor to unlock it.'
    );
  end if;

  select * into v_member from public.organization_members where id = v_cred.member_id;
  if v_member.id is null or not v_member.is_active then
    return jsonb_build_object('ok', false, 'error', 'Worker access has been revoked.');
  end if;

  if not verify_worker_pin(trim(p_pin), v_cred.pin_hash) then
    update public.floor_worker_credentials
    set failed_attempts = failed_attempts + 1,
        locked_until = case when failed_attempts + 1 >= 5 then now() + interval '15 minutes' else null end,
        updated_at = now()
    where id = v_cred.id;

    if v_cred.failed_attempts + 1 >= 5 then
      return jsonb_build_object('ok', false, 'locked', true,
        'error', 'Too many failed attempts. Account locked for 15 minutes.');
    end if;
    return jsonb_build_object('ok', false,
      'error', 'Incorrect PIN. ' || (5 - (v_cred.failed_attempts + 1))::text || ' attempts remaining.');
  end if;

  -- Device: known devices must belong to this organization; unknown ones are
  -- registered as unauthorized so a supervisor can approve them.
  if v_device_token is not null then
    if char_length(v_device_token) > 100 then
      return jsonb_build_object('ok', false, 'error', 'Invalid device identifier.');
    end if;
    select * into v_device from public.floor_devices where device_token = v_device_token;
    if v_device.id is null then
      insert into public.floor_devices (organization_id, device_name, device_token, is_authorized, device_type)
      values (v_member.organization_id, 'New device ' || upper(left(v_device_token, 6)), v_device_token, false, 'browser')
      returning * into v_device;
    elsif v_device.organization_id <> v_member.organization_id then
      return jsonb_build_object('ok', false, 'error', 'This device is registered to another organization.');
    elsif v_device.retired_at is not null then
      return jsonb_build_object('ok', false, 'error', 'This device has been retired. Ask a supervisor to re-register it.');
    end if;
    update public.floor_devices set last_active_at = now() where id = v_device.id;
  end if;

  update public.floor_worker_credentials
  set failed_attempts = 0, locked_until = null, last_signed_in_at = now(), updated_at = now()
  where id = v_cred.id;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.floor_sessions (token_hash, credential_id, member_id, organization_id, device_id, expires_at)
  values (_hash_session_token(v_token), v_cred.id, v_member.id, v_member.organization_id, v_device.id, v_expires);

  select * into v_profile from public.profiles where id = v_member.user_id;
  select * into v_org from public.organizations where id = v_member.organization_id;

  return jsonb_build_object(
    'ok', true,
    'session_token', v_token,
    'session_expires_at', v_expires,
    'worker_code', v_cred.worker_code,
    'first_name', v_profile.first_name,
    'last_name', v_profile.last_name,
    'organization_id', v_org.id,
    'organization_name', v_org.name,
    'member_id', v_member.id,
    'all_facilities', v_member.all_facilities,
    'device', case when v_device.id is null then null else jsonb_build_object(
      'id', v_device.id, 'name', v_device.device_name,
      'is_authorized', v_device.is_authorized, 'is_blocked', v_device.blocked_at is not null,
      'facility_id', v_device.facility_id) end
  );
end;
$$;

-- --------------------------------------------------------------------
-- Entry point 2: floor terminals (badge + PIN session)
-- Organization, worker and device come from the session, never the client.
-- The facility defaults to the device's facility.
-- --------------------------------------------------------------------
create or replace function public._record_floor_event(p_session public.floor_sessions, p_event jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_facility_id uuid := (p_event ->> 'facility_id')::uuid;
  v_member      public.organization_members;
  v_device      public.floor_devices;
begin
  if p_session.device_id is null then
    perform _event_error('device_required', 'Floor events must come from a registered device', '42501');
  end if;

  -- Device status first: an unapproved terminal needs a supervisor, not a facility.
  select * into v_device from floor_devices where id = p_session.device_id;
  if v_device.retired_at is not null then
    perform _event_error('device_retired', 'This device has been retired', '42501');
  elsif v_device.blocked_at is not null then
    perform _event_error('device_blocked', 'This device has been blocked by a supervisor', '42501');
  elsif not v_device.is_authorized then
    perform _event_error('device_not_authorized', 'This device is waiting for a supervisor to authorize it', '42501');
  end if;

  v_facility_id := coalesce(v_facility_id, v_device.facility_id);
  if v_facility_id is null then
    perform _event_error('facility_required', 'Assign this device to a facility before recording floor events', '22023');
  end if;
  if not _member_has_facility(p_session.member_id, v_facility_id) then
    perform _event_error('scope_denied', 'You do not have access to this facility', '42501');
  end if;
  if nullif(trim(p_event ->> 'backdate_reason'), '') is not null then
    perform _event_error('backdate_not_allowed', 'Floor terminals cannot record back-dated events', '42501');
  end if;

  select * into v_member from organization_members where id = p_session.member_id;

  return _insert_event(
    p_session.organization_id,
    jsonb_set(p_event - 'device_id', '{facility_id}', to_jsonb(v_facility_id)),
    v_member.user_id, p_session.credential_id, p_session.device_id,
    'floor', false, null
  );
end;
$$;

create or replace function public.record_floor_event(p_session_token text, p_event jsonb)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
begin
  return (_record_floor_event(_floor_session(p_session_token), p_event) ->> 'event_id')::uuid;
end;
$$;

create or replace function public.record_floor_events(p_session_token text, p_events jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.floor_sessions := _floor_session(p_session_token);
  v_results jsonb := '[]'::jsonb;
  v_result  jsonb;
  v_code    text;
  v_message text;
  v_i       integer;
begin
  if jsonb_typeof(p_events) <> 'array' then
    perform _event_error('invalid_batch', 'events must be a JSON array', '22023');
  end if;
  if jsonb_array_length(p_events) > 100 then
    perform _event_error('batch_too_large', 'A batch can contain at most 100 events', '22023');
  end if;

  for v_i in 0 .. jsonb_array_length(p_events) - 1 loop
    v_result := null; v_code := null; v_message := null;
    begin
      v_result := _record_floor_event(v_session, p_events -> v_i);
    exception when others then
      get stacked diagnostics v_code = pg_exception_hint, v_message = message_text;
    end;
    v_results := v_results || _event_result(v_i, v_result, v_code, v_message);
  end loop;
  return v_results;
end;
$$;

-- --------------------------------------------------------------------
-- Entry point 3: trusted server code (service_role only)
-- Integrations, the public API service layer, migrations and system jobs.
-- --------------------------------------------------------------------
create or replace function public.record_system_event(p_organization_id uuid, p_event jsonb, p_source text default 'system')
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_source not in ('system', 'integration', 'api', 'migration') then
    perform _event_error('invalid_source', 'source must be system, integration, api or migration', '22023');
  end if;
  if not exists (select 1 from organizations where id = p_organization_id) then
    perform _event_error('scope_denied', 'Unknown organization', '42501');
  end if;

  return _insert_event(
    p_organization_id, p_event,
    null, null, (p_event ->> 'device_id')::uuid,
    p_source,
    -- Migration imports carry historical timestamps by design
    p_source = 'migration' or nullif(trim(p_event ->> 'backdate_reason'), '') is not null,
    null
  );
end;
$$;

-- --------------------------------------------------------------------
-- Device management (owner, admin, ops_manager, supervisor)
-- --------------------------------------------------------------------
create or replace function public._require_device_manager(p_organization_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null
     or coalesce(get_user_role(p_organization_id)::text, '') not in ('owner', 'admin', 'ops_manager', 'supervisor') then
    perform _event_error('scope_denied', 'Only supervisors and above can manage devices', '42501');
  end if;
end;
$$;

create or replace function public.register_device(
  p_organization_id uuid,
  p_device_token    text,
  p_device_name     text,
  p_device_type     text default 'browser',
  p_facility_id     uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token  text := nullif(trim(coalesce(p_device_token, '')), '');
  v_name   text := nullif(trim(coalesce(p_device_name, '')), '');
  v_device public.floor_devices;
begin
  perform _require_device_manager(p_organization_id);

  if v_token is null or char_length(v_token) > 100 then
    perform _event_error('invalid_device', 'A device identifier is required', '22023');
  end if;
  if v_name is null or char_length(v_name) > 80 then
    perform _event_error('invalid_device', 'Device name must be 1 to 80 characters', '22023');
  end if;
  if p_facility_id is not null and not exists (
    select 1 from facilities where id = p_facility_id and organization_id = p_organization_id
  ) then
    perform _event_error('scope_denied', 'Facility does not belong to this organization', '42501');
  end if;

  select * into v_device from floor_devices where device_token = v_token;
  if v_device.id is not null and v_device.organization_id <> p_organization_id then
    perform _event_error('scope_denied', 'This device is registered to another organization', '42501');
  end if;

  insert into floor_devices (organization_id, facility_id, device_name, device_token, device_type,
                             is_authorized, registered_by, retired_at, updated_at)
  values (p_organization_id, p_facility_id, v_name, v_token, coalesce(p_device_type, 'browser'),
          true, auth.uid(), null, now())
  on conflict (device_token) do update
    set device_name   = excluded.device_name,
        facility_id   = coalesce(excluded.facility_id, floor_devices.facility_id),
        device_type   = excluded.device_type,
        is_authorized = true,
        registered_by = excluded.registered_by,
        retired_at    = null,
        blocked_at    = null,
        blocked_by    = null,
        updated_at    = now()
  returning * into v_device;

  return v_device.id;
end;
$$;

create or replace function public.update_device(
  p_device_id     uuid,
  p_device_name   text    default null,
  p_facility_id   uuid    default null,
  p_is_authorized boolean default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_device public.floor_devices;
  v_name   text := nullif(trim(coalesce(p_device_name, '')), '');
begin
  select * into v_device from floor_devices where id = p_device_id;
  if v_device.id is null then
    perform _event_error('unknown_device', 'Device not found', '22023');
  end if;
  perform _require_device_manager(v_device.organization_id);

  if v_device.retired_at is not null then
    perform _event_error('device_retired', 'Retired devices cannot be changed; register it again instead', '22023');
  end if;
  if v_name is not null and char_length(v_name) > 80 then
    perform _event_error('invalid_device', 'Device name must be 1 to 80 characters', '22023');
  end if;
  if p_facility_id is not null and not exists (
    select 1 from facilities where id = p_facility_id and organization_id = v_device.organization_id
  ) then
    perform _event_error('scope_denied', 'Facility does not belong to this organization', '42501');
  end if;

  update floor_devices
  set device_name   = coalesce(v_name, device_name),
      facility_id   = coalesce(p_facility_id, facility_id),
      is_authorized = coalesce(p_is_authorized, is_authorized),
      blocked_at    = case when p_is_authorized is false then now()
                         when p_is_authorized is true then null
                         else blocked_at end,
      blocked_by    = case when p_is_authorized is false then auth.uid()
                         when p_is_authorized is true then null
                         else blocked_by end,
      updated_at    = now()
  where id = p_device_id;

  -- De-authorizing a device ends its floor sessions immediately
  if p_is_authorized is false then
    update floor_sessions set revoked_at = now() where device_id = p_device_id and revoked_at is null;
  end if;
end;
$$;

create or replace function public.retire_device(p_device_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_org uuid;
begin
  select organization_id into v_org from floor_devices where id = p_device_id;
  if v_org is null then
    perform _event_error('unknown_device', 'Device not found', '22023');
  end if;
  perform _require_device_manager(v_org);

  update floor_devices
  set retired_at = coalesce(retired_at, now()), is_authorized = false, updated_at = now()
  where id = p_device_id;
  update floor_sessions set revoked_at = now() where device_id = p_device_id and revoked_at is null;
end;
$$;

