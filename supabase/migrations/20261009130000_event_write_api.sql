-- ====================================================================
-- Phase 1 · Sprint 2 · Step 2 — Event Write API, Floor Sessions & Devices
-- ====================================================================
-- Every producer records events through one of three entry points, all of
-- which share the same validated, idempotent insert (_insert_event):
--
--   record_event / record_events            signed-in members (admin web app)
--   record_floor_event / record_floor_events floor terminals (badge + PIN session)
--   record_system_event                      trusted server code (service_role only)
--
-- Also in this migration:
--   * validate_event_payload: JSON-schema subset validator (no extension needed)
--   * floor_sessions: server-side floor sessions. The old vp_floor_session
--     cookie held unsigned JSON (worker/org IDs) that a user could edit to
--     impersonate any worker; the cookie now holds only an opaque token whose
--     SHA-256 hash is stored here.
--   * device registry: unknown devices are auto-registered as unauthorized at
--     floor login; supervisors+ register, rename, authorize and retire them.
--
-- Errors raise with a stable machine code in HINT (e.g. 'scope_denied') so the
-- batch functions and the app can report them per event.
-- ====================================================================

